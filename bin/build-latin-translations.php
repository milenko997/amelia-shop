<?php
/**
 * Builds Serbian Latin translations from the official Serbian Cyrillic (sr_RS) ones.
 *
 * Reads the sr_RS .l10n.php files that WordPress downloads into wp-content/languages,
 * transliterates every translation to Latin and writes the result to languages/.
 * The theme loads these files on the frontend (see inc/i18n.php).
 *
 * Run after updating WordPress or WooCommerce (and their translations):
 *   npm run translations
 */

if ( PHP_SAPI !== 'cli' ) {
	exit( 1 );
}

$theme_dir = dirname( __DIR__ );
$lang_dir  = dirname( $theme_dir, 2 ) . '/languages';

$sources = [
	'woocommerce' => $lang_dir . '/plugins/woocommerce-sr_RS.l10n.php',
	'default'     => $lang_dir . '/sr_RS.l10n.php',
];

$map = [
	'Љ' => 'Lj', 'Њ' => 'Nj', 'Џ' => 'Dž',
	'љ' => 'lj', 'њ' => 'nj', 'џ' => 'dž',
	'А' => 'A', 'Б' => 'B', 'В' => 'V', 'Г' => 'G', 'Д' => 'D', 'Ђ' => 'Đ', 'Е' => 'E', 'Ж' => 'Ž',
	'З' => 'Z', 'И' => 'I', 'Ј' => 'J', 'К' => 'K', 'Л' => 'L', 'М' => 'M', 'Н' => 'N', 'О' => 'O',
	'П' => 'P', 'Р' => 'R', 'С' => 'S', 'Т' => 'T', 'Ћ' => 'Ć', 'У' => 'U', 'Ф' => 'F', 'Х' => 'H',
	'Ц' => 'C', 'Ч' => 'Č', 'Ш' => 'Š',
	'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'ђ' => 'đ', 'е' => 'e', 'ж' => 'ž',
	'з' => 'z', 'и' => 'i', 'ј' => 'j', 'к' => 'k', 'л' => 'l', 'м' => 'm', 'н' => 'n', 'о' => 'o',
	'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'ћ' => 'ć', 'у' => 'u', 'ф' => 'f', 'х' => 'h',
	'ц' => 'c', 'ч' => 'č', 'ш' => 'š',
];

$transliterate = function ( string $text ) use ( $map ): string {
	// Digraph letters in all-caps words: "ЉУБАВ" -> "LJUBAV", not "LjUBAV".
	$text = preg_replace_callback(
		'/([ЉЊЏ])(?=[А-ЯЂЈЉЊЋЏ])/u',
		fn( $m ) => mb_strtoupper( $map[ $m[1] ] ),
		$text
	);
	return strtr( $text, $map );
};

foreach ( $sources as $domain => $source ) {
	if ( ! is_readable( $source ) ) {
		fwrite( STDERR, "Missing {$source} (install the sr_RS language pack first).\n" );
		exit( 1 );
	}

	$data = include $source;
	$data['language'] = 'sr_RS@latin';
	$data['messages'] = array_map( $transliterate, $data['messages'] );

	$target = "{$theme_dir}/languages/{$domain}-sr_Latn.l10n.php";
	if ( ! is_dir( dirname( $target ) ) ) {
		mkdir( dirname( $target ), 0755, true );
	}
	file_put_contents( $target, "<?php\n// Generated by bin/build-latin-translations.php from " . ( $data['project-id-version'] ?? $domain ) . " (" . ( $data['translation-revision-date'] ?? '' ) . "). Do not edit.\nreturn " . var_export( $data, true ) . ";\n" );

	printf( "%s: %d strings -> %s\n", $domain, count( $data['messages'] ), str_replace( $theme_dir . '/', '', $target ) );
}
